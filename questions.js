  getQuestions(genreId, count = 30) {
    let pool = [];
    if (genreId === 'random') {
      Object.values(this.questions).forEach(arr => pool.push(...arr));
    } else {
      pool = this.questions[genreId] || [];
    }
    // シャッフルして指定数を返す
    const shuffled = pool.sort(() => Math.random() - 0.5);
    return shuffled.slice(0, Math.min(count, shuffled.length));
  },

  countAll() {
    return Object.values(this.questions).reduce((sum, arr) => sum + arr.length, 0);
  }
